# Lists the radio voice files in Speak/ for the game: js/ui/voices.js (a browser can't list a folder by itself).
#   python tools/voices.py
# Speak/<Language>/<event>/<Voice>_<n>.mp3 — Language: English or Hebrew; event: one of EVENTS. The game plays any
# of an event's files at random (not the same one twice running). And the explanations (js/ui/advisor.js):
# Speak/<Language>/Instructions/<id>.mp3 → ADVICE_REC (tools/eleven_advice.py makes them).
import json, os

ROOT = os.path.join(os.path.dirname(__file__), '..')
EVENTS = ['selected', 'on_the_way', 'attacking', 'holding', 'retreating', 'in_position', 'under_attack', 'heavy_losses',
          'squad_lost', 'friendly_fire', 'promoted', 'say_again', 'forward_hq', 'building_lost',
          'base_attack', 'fhq_attack', 'hq_attack', 'drone_lost',
          'dozer_ready', 'dozer_idle', 'radio_ready', 'fhq_ready', 'drone_ready', 'place_hq', 'hq_ready',
          'took_radar', 'took_power', 'took_fuel', 'took_post', 'lost_post', 'can_build',
          'missile_incoming', 'intercepted',
          'report_fuel', 'report_food', 'report_ammo', 'report_hurt',
          'ask_ok', 'ask_none', 'ask_making', 'mate_fuel', 'mate_ammo', 'mate_food', 'mate_fire', 'mate_guard',
          'front_contact', 'front_pressure', 'front_ready']
AUDIO = ('.mp3', '.wav', '.ogg', '.m4a')
LANG_KEY = {'English': 'en', 'Hebrew': 'he'}

def build():
    out, rec = {}, {}
    base = os.path.join(ROOT, 'Speak')
    for lang in sorted(os.listdir(base)) if os.path.isdir(base) else []:
        if not os.path.isdir(os.path.join(base, lang)): continue
        for ev in EVENTS:
            d = os.path.join(base, lang, ev)
            if not os.path.isdir(d): continue
            files = [f for f in sorted(os.listdir(d)) if os.path.splitext(f)[1].lower() in AUDIO]
            if files: out.setdefault(lang, {})[ev] = [f'Speak/{lang}/{ev}/{f}' for f in files]
        d = os.path.join(base, lang, 'Instructions')
        if os.path.isdir(d) and lang in LANG_KEY:
            for f in sorted(os.listdir(d)):
                n, x = os.path.splitext(f)
                if x.lower() in AUDIO: rec.setdefault(LANG_KEY[lang], {})[n] = f'Speak/{lang}/Instructions/{f}'
        unknown = [f for f in os.listdir(os.path.join(base, lang)) if f not in EVENTS and f != 'Instructions']
        if unknown: print(f'  {lang}: not an event folder, skipped: {", ".join(unknown)}')
    js = '// generated by tools/voices.py from Speak/ — do not edit by hand\nconst VOICES = ' + json.dumps(out, ensure_ascii=False, indent=1) + ';\n' \
        + 'const ADVICE_REC = ' + json.dumps(rec, ensure_ascii=False, indent=1) + ';\n'
    open(os.path.join(ROOT, 'js', 'ui', 'voices.js'), 'w', encoding='utf-8').write(js)
    for lang, evs in out.items(): print(lang, ', '.join(f'{e} {len(f)}' for e, f in evs.items()))
    for lang, ids in rec.items(): print(f'Instructions {lang}: {len(ids)}')
    missing(out, rec)

# Speak/Missing_recordings.md: what has no recording yet (the game reads those aloud with the browser's voice) — the
# radio events with no take at all (their lines: tools/eleven.py), and the explanations not recorded (their lines:
# Speak/Advice_lines.csv; tools/eleven_advice.py). Written on every run, so it's always up to date.
def missing(out, rec):
    import csv, sys
    sys.path.insert(0, os.path.dirname(__file__)); import eleven
    md = ['# Missing recordings', '', 'Generated by `python tools/voices.py` — do not edit by hand. Until these are recorded,',
          "the game reads them aloud with the browser's voice.", '']
    md += ['## Radio (`python tools/eleven.py`)', '', '| event | English | עברית |', '|---|---|---|']
    n_radio = 0
    for ev in EVENTS:
        en, he = ev not in out.get('English', {}), ev not in out.get('Hebrew', {})
        if en or he:
            n_radio += en + he
            md.append(f'| `{ev}` | {eleven.LINES["English"].get(ev, ["?"])[0] if en else "✓"} | {eleven.LINES["Hebrew"].get(ev, ["?"])[0] if he else "✓"} |')
    md += ['', '## Explanations (`python tools/eleven_advice.py` → `Speak/<English|Hebrew>/Instructions/<id>.mp3`)', '',
           '| file | English | עברית |', '|---|---|---|']
    n_adv = 0
    f = os.path.join(ROOT, 'Speak', 'Advice_lines.csv')
    if os.path.exists(f):
        for r in csv.DictReader(open(f, encoding='utf-8-sig', newline='')):
            en, he = r['id'] not in rec.get('en', {}), r['id'] not in rec.get('he', {})
            if en or he:
                n_adv += en + he
                md.append(f"| `{r['id']}.mp3` | {r['en'] if en else '✓'} | {r['he'] if he else '✓'} |")
    md[4:4] = ['', f'{n_radio} radio events and {n_adv} explanation lines missing (counting each language).']
    open(os.path.join(ROOT, 'Speak', 'Missing_recordings.md'), 'w', encoding='utf-8').write('\n'.join(md) + '\n')
    print(f'Missing: {n_radio} radio events, {n_adv} explanation lines -> Speak/Missing_recordings.md')

if __name__ == '__main__': build()
