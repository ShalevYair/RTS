// The explanations' lines (js/ui/advice.js) → Speak/Advice_lines.md: for each, the file to record it into
// (Speak/English/Instructions/<id>.mp3, Speak/Hebrew/Instructions/<id>.mp3), its English and its Hebrew — and Speak/Advice_lines.csv
// (id, en, he) for a script. Run: node tools/advice_list.js
const fs = require('fs'), path = require('path');
const ROOT = path.join(__dirname, '..');
const Sim = require(path.join(ROOT, 'tests', 'load-sim.js'))();
const { adviceLines } = require(path.join(ROOT, 'js', 'ui', 'advice.js'));
// (the English building names: lang.js's EN_STRUCTS line)
const m = fs.readFileSync(path.join(ROOT, 'js', 'ui', 'lang.js'), 'utf8').match(/const EN_STRUCTS = (\{[^\n]*\});/);
const EN = Function('return ' + m[1])();
const L = adviceLines(Sim, EN), ids = Object.keys(L);
const group = id => id.startsWith('intro_') || id.startsWith('arms_') || id.startsWith('hq_') ? 'פתיחה · Opening'
  : id.startsWith('step_') || id === 'con_ready' || id.startsWith('matechain_') ? 'שרשרת האספקה · Supply chain'
  : id.startsWith('open_') ? 'נפתח · Opened'
  : id.startsWith('why_') || id.startsWith('need') || id === 'tech' ? 'למה לא · Why not' : 'יכולת חדשה · New';
let md = '# Explanations — lines to record\n\nGenerated by `node tools/advice_list.js` from `js/ui/advice.js` — do not edit by hand.\n\n'
  + 'Each line goes in its own file: `Speak/English/Instructions/<id>.mp3` and `Speak/Hebrew/Instructions/<id>.mp3`.\n'
  + `${ids.length} lines · ${ids.reduce((a, k) => a + L[k].en.length, 0)} characters in English · ${ids.reduce((a, k) => a + L[k].he.length, 0)} in Hebrew.\n`;
let last = '';
for (const id of ids) {
  const g = group(id); if (g !== last) { md += `\n## ${g}\n\n| file | English | עברית |\n|---|---|---|\n`; last = g; }
  md += `| \`${id}.mp3\` | ${L[id].en.replace(/\|/g, '\\|')} | ${L[id].he.replace(/\|/g, '\\|')} |\n`;
}
const out = path.join(ROOT, 'Speak'); fs.mkdirSync(out, { recursive: true });
fs.writeFileSync(path.join(out, 'Advice_lines.md'), md);
const q = t => '"' + t.replace(/"/g, '""') + '"';
fs.writeFileSync(path.join(out, 'Advice_lines.csv'), '﻿id,en,he\n' + ids.map(id => [id, q(L[id].en), q(L[id].he)].join(',')).join('\n') + '\n');
console.log(ids.length, 'lines → Speak/Advice_lines.md, Speak/Advice_lines.csv');
