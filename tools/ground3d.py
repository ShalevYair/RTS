"""The 3D view's ground textures: art/Ground3D/<layer>_{diff,nor}.jpg (Poly Haven, CC0 — the sources at 2K, see
LAYERS) → 1024 px JPEGs → js/ui/ground3d.js (data URIs, so the page works from file:// too; loaded with the 3D view
only). Run: python tools/ground3d.py [folder with the Poly Haven 2K jpgs] — with a folder, the art/Ground3D files are
made from it first (<asset>_diff.jpg, <asset>_nor_gl.jpg)."""
import base64, io, os, sys
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ART = os.path.join(ROOT, 'art', 'Ground3D')
OUT = os.path.join(ROOT, 'js', 'ui', 'ground3d.js')
# layer → Poly Haven asset; which have their own normal map (the rest borrow one — fewer samplers in the shader)
LAYERS = {'grass': 'rocky_terrain_02', 'grass2': 'forrest_ground_01', 'dry': 'aerial_grass_rock', 'dirt': 'dirt_aerial_02', 'rock': 'aerial_rocks_02', 'mud': 'brown_mud_leaves_01'}
NORMALS = ('grass', 'dirt', 'rock')
# the buildings' surfaces (BLD3D: floors, walls, the painted metal roofs) — at 1K from the folder's bld/ (<asset>_diff.jpg, _nor_gl.jpg)
BLD = {'floor': 'concrete_floor_worn_001', 'wall': 'concrete_wall_008', 'metal': 'box_profile_metal_sheet'}
# the units' paint (UNIT3D: worn army-painted metal — its light and dark and its dents over the models' own colours) — from unit/
UNIT = {'paint': 'green_metal_rust'}
SIZE = 1024


def jpg(im, q):
    b = io.BytesIO(); im.save(b, 'JPEG', quality=q, optimize=True); return b.getvalue()


def main():
    os.makedirs(ART, exist_ok=True)
    if len(sys.argv) > 1:
        src = sys.argv[1]
        for k, a in LAYERS.items():
            Image.open(os.path.join(src, a + '_diff.jpg')).convert('RGB').resize((SIZE, SIZE), Image.LANCZOS).save(os.path.join(ART, k + '_diff.jpg'), quality=88)
            if k in NORMALS:
                Image.open(os.path.join(src, a + '_nor_gl.jpg')).convert('RGB').resize((SIZE, SIZE), Image.LANCZOS).save(os.path.join(ART, k + '_nor.jpg'), quality=92)
        for k, a in BLD.items():
            for m, o in (('diff', 'diff'), ('nor_gl', 'nor')):
                Image.open(os.path.join(src, 'bld', f'{a}_{m}.jpg')).convert('RGB').resize((SIZE, SIZE), Image.LANCZOS).save(os.path.join(ART, f'b{k}_{o}.jpg'), quality=90)
        for k, a in UNIT.items():
            for m, o in (('diff', 'diff'), ('nor_gl', 'nor')):
                Image.open(os.path.join(src, 'unit', f'{a}_{m}.jpg')).convert('RGB').resize((SIZE, SIZE), Image.LANCZOS).save(os.path.join(ART, f'u{k}_{o}.jpg'), quality=90)
    lines = ['// generated by tools/ground3d.py from art/Ground3D (Poly Haven, CC0) — do not edit by hand', 'const GROUND3D = {']
    for k in LAYERS:
        ent = []
        for m, q in (('diff', 84), ('nor', 90)):
            p = os.path.join(ART, f'{k}_{m}.jpg')
            if os.path.exists(p):
                ent.append(f"{m[0]}: 'data:image/jpeg;base64,{base64.b64encode(jpg(Image.open(p).convert('RGB'), q)).decode()}'")
        lines.append(f'  {k}: {{ {", ".join(ent)} }},')
    lines.append('};')
    lines.append('const BLD3D = {')
    for k in BLD:
        ent = [f"{m[0]}: 'data:image/jpeg;base64,{base64.b64encode(jpg(Image.open(os.path.join(ART, f'b{k}_{m}.jpg')).convert('RGB'), q)).decode()}'" for m, q in (('diff', 84), ('nor', 90)) if os.path.exists(os.path.join(ART, f'b{k}_{m}.jpg'))]
        lines.append(f'  {k}: {{ {", ".join(ent)} }},')
    lines.append('};')
    lines.append('const UNIT3D = {')
    for k in UNIT:
        ent = [f"{m[0]}: 'data:image/jpeg;base64,{base64.b64encode(jpg(Image.open(os.path.join(ART, f'u{k}_{m}.jpg')).convert('RGB'), q)).decode()}'" for m, q in (('diff', 84), ('nor', 90)) if os.path.exists(os.path.join(ART, f'u{k}_{m}.jpg'))]
        lines.append(f'  {k}: {{ {", ".join(ent)} }},')
    lines.append('};')
    open(OUT, 'w', encoding='utf-8').write('\n'.join(lines) + '\n')
    print(OUT, os.path.getsize(OUT) // 1024, 'KB')


if __name__ == '__main__':
    main()
